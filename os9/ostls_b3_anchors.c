static br_x509_trust_anchor g_anchors[OSTLS_B3_NUM_ANCHORS];
static int g_anchors_initialized = 0;


/*
 * Initialise one RSA trust anchor slot in-place. Called below for
 * every RSA TA so the runtime init reads as a flat table instead of
 * five duplicated 8-line blocks.
 */
static void
init_rsa_anchor(int slot,
    const unsigned char *dn, size_t dn_len,
    const unsigned char *n,  size_t n_len,
    const unsigned char *e,  size_t e_len)
{
    g_anchors[slot].dn.data         = (unsigned char *)dn;
    g_anchors[slot].dn.len          = dn_len;
    g_anchors[slot].flags           = BR_X509_TA_CA;
    g_anchors[slot].pkey.key_type   = BR_KEYTYPE_RSA;
    g_anchors[slot].pkey.key.rsa.n     = (unsigned char *)n;
    g_anchors[slot].pkey.key.rsa.nlen  = n_len;
    g_anchors[slot].pkey.key.rsa.e     = (unsigned char *)e;
    g_anchors[slot].pkey.key.rsa.elen  = e_len;
}


/*
 * Initialise one EC trust anchor slot in-place. All currently-
 * embedded EC anchors are on secp384r1; if a future root uses a
 * different curve, add a `curve` parameter rather than hardcoding.
 */
static void
init_ec_anchor(int slot,
    const unsigned char *dn, size_t dn_len,
    const unsigned char *q,  size_t q_len)
{
    g_anchors[slot].dn.data         = (unsigned char *)dn;
    g_anchors[slot].dn.len          = dn_len;
    g_anchors[slot].flags           = BR_X509_TA_CA;
    g_anchors[slot].pkey.key_type   = BR_KEYTYPE_EC;
    g_anchors[slot].pkey.key.ec.curve = BR_EC_secp384r1;
    g_anchors[slot].pkey.key.ec.q     = (unsigned char *)q;
    g_anchors[slot].pkey.key.ec.qlen  = q_len;
}


static void
b3_init_anchors_once(void)
{
    if (g_anchors_initialized) {
        return;
    }

    /* TA0 -- Amazon Root CA 1 (RSA-2048) */
    init_rsa_anchor(0, TA0_DN, sizeof TA0_DN,
                       TA0_RSA_N, sizeof TA0_RSA_N,
                       TA0_RSA_E, sizeof TA0_RSA_E);

    /* TA1 -- DigiCert Global Root G2 (RSA-2048) */
    init_rsa_anchor(1, TA1_DN, sizeof TA1_DN,
                       TA1_RSA_N, sizeof TA1_RSA_N,
                       TA1_RSA_E, sizeof TA1_RSA_E);

    /* TA2 -- GTS Root R1 (RSA-4096, Google primary RSA root) */
    init_rsa_anchor(2, TA2_DN, sizeof TA2_DN,
                       TA2_RSA_N, sizeof TA2_RSA_N,
                       TA2_RSA_E, sizeof TA2_RSA_E);

    /* TA3 -- GTS Root R4 (EC P-384, Google ECDSA chain) */
    init_ec_anchor(3, TA3_DN, sizeof TA3_DN,
                      TA3_EC_Q, sizeof TA3_EC_Q);

    /* TA4 -- ISRG Root X1 (RSA-4096, Let's Encrypt) */
    init_rsa_anchor(4, TA4_DN, sizeof TA4_DN,
                       TA4_RSA_N, sizeof TA4_RSA_N,
                       TA4_RSA_E, sizeof TA4_RSA_E);

    /* TA5 -- ISRG Root X2 (EC P-384, Let's Encrypt ECDSA chain) */
    init_ec_anchor(5, TA5_DN, sizeof TA5_DN,
                      TA5_EC_Q, sizeof TA5_EC_Q);

    /* TA6 -- GTS Root R2 (RSA-4096, Google secondary RSA) */
    init_rsa_anchor(6, TA6_DN, sizeof TA6_DN,
                       TA6_RSA_N, sizeof TA6_RSA_N,
                       TA6_RSA_E, sizeof TA6_RSA_E);

    /* TA7 -- GTS Root R3 (EC P-384, Google ECDSA) */
    init_ec_anchor(7, TA7_DN, sizeof TA7_DN,
                      TA7_EC_Q, sizeof TA7_EC_Q);

    /* TA8 -- DigiCert Global Root G3 (EC P-384) */
    init_ec_anchor(8, TA8_DN, sizeof TA8_DN,
                      TA8_EC_Q, sizeof TA8_EC_Q);

    /* TA9 -- Starfield Services Root CA G2 (RSA-2048) */
    init_rsa_anchor(9, TA9_DN, sizeof TA9_DN,
                       TA9_RSA_N, sizeof TA9_RSA_N,
                       TA9_RSA_E, sizeof TA9_RSA_E);

    g_anchors_initialized = 1;
}


void
OSTLS_B3_GetAnchors(const br_x509_trust_anchor **out_anchors,
                    size_t *out_count)
{
    b3_init_anchors_once();
    if (out_anchors != NULL) {
        *out_anchors = g_anchors;
    }
    if (out_count != NULL) {
        *out_count = OSTLS_B3_NUM_ANCHORS;
    }
}
